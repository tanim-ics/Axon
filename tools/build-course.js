'use strict';
/* One-off converter, not part of the running app:  node tools/build-course.js
   Reads course/addy/md/NN.md (Addy Osmani's "Agent Engineer" lessons, Apache 2.0) and writes
   course/addy/NN.js, which the reader loads with a <script> tag (so the CSP needs no connect-src).
   The lessons as published embed interactive HTML widgets with inline <script>. Those are removed
   here and replaced by a one-line note, and the cleaned text is written back to md/NN.md, so no
   third-party script is stored in this project at all. Running it again changes nothing.
   After downloading a fresh copy of a lesson into md/, run this before anything else. */
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '..', 'course', 'addy');
const NOTE = '> The original lesson has an interactive demo here. Open the original to try it.';

function strip(md) {
  const out = [];
  let fence = false, depth = 0, script = false;
  md.replace(/\r\n?/g, '\n').split('\n').forEach((line) => {
    if (!depth && !script && /^\s*```/.test(line)) { fence = !fence; out.push(line); return; }
    if (fence) { out.push(line); return; }
    if (script) { if (/<\/(script|style)>/i.test(line)) script = false; return; }
    if (/^\s*<(script|style)\b/i.test(line)) { script = !/<\/(script|style)>/i.test(line); return; }
    if (depth || /^\s*<div\b/i.test(line)) {
      if (!depth) out.push('', NOTE, '');
      depth += (line.match(/<div\b/gi) || []).length - (line.match(/<\/div>/gi) || []).length;
      if (depth < 0) depth = 0;
      return;
    }
    out.push(line);
  });
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

let count = 0, cleaned = 0;
fs.readdirSync(path.join(dir, 'md')).filter((f) => /^\d\d\.md$/.test(f)).sort().forEach((f) => {
  const no = f.slice(0, 2);
  const raw = fs.readFileSync(path.join(dir, 'md', f), 'utf8');
  const text = strip(raw);
  const tooLong = text.split('\n').find((l) => l.length > 5000);
  if (tooLong) throw new Error(f + ': a line of ' + tooLong.length + ' characters; check the source before bundling it');
  let inFence = false;
  const leftovers = text.split('\n').filter((l) => {
    if (/^\s*```/.test(l)) inFence = !inFence;
    return !inFence && /^\s*<\/?[a-zA-Z]/.test(l);
  });
  if (leftovers.length) throw new Error(f + ': HTML left after stripping: ' + leftovers[0].slice(0, 80));
  if (text !== raw) { fs.writeFileSync(path.join(dir, 'md', f), text); cleaned++; }
  const js = JSON.stringify(text).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029').replace(/<\//g, '<\\/');
  fs.writeFileSync(path.join(dir, no + '.js'), '/* Generated by tools/build-course.js from md/' + f +
    '. Source: github.com/addyosmani/agent-engineer (Apache 2.0). */\nCourse.add(' + JSON.stringify(no) + ', ' + js + ');\n');
  count++;
});
console.log('wrote ' + count + ' lessons; removed embedded HTML from ' + cleaned + ' stored files');
